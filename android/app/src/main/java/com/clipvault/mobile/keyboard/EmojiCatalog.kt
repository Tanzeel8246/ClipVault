    /**
     * Search emojis based on query. Supports partial matching across English and Urdu/Roman Urdu tags.
     */
    fun search(query: String): List<String> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return emptyList()

        val results = mutableListOf<String>()

        // 1. Direct tag match
        searchIndex[q]?.let { results.addAll(it) }

        // 2. Substring tag match
        for ((tag, emojis) in searchIndex) {
            if (tag.contains(q) || q.contains(tag)) {
                for (e in emojis) {
                    if (!results.contains(e)) results.add(e)
                }
            }
            if (results.size >= 40) break
        }

        return results.distinct()
    }

    /**
     * Predict relevant contextual emojis for a given word or short sentence.
     * Used for inline suggestion strip chips.
     */
    fun suggestContextEmojis(input: String): List<String> {
        val clean = input.trim().lowercase()
        if (clean.isEmpty()) return emptyList()

        // Check exact match
        searchIndex[clean]?.let { return it.take(3) }

        // Check if words in input match
        val words = clean.split(Regex("\\s+"))
        for (w in words.reversed()) {
            searchIndex[w]?.let { return it.take(3) }
        }

        return emptyList()
    }
